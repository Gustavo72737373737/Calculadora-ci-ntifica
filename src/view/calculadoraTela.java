    private void inversorSinalButtonActionPerformed(java.awt.event.ActionEvent evt) {
        limparErroSeExistir();
        String t = resultado.getText();
        if (t.isEmpty()) return;
        if (t.startsWith("-(") && t.endsWith(")")) {
            resultado.setText(t.substring(2, t.length() - 1)); // remove o sinal
        } else {
            resultado.setText("-(" + t + ")");
        }
    }

