    private void apagarButtonActionPerformed(java.awt.event.ActionEvent evt) {
        String t = resultado.getText();
        if (t.equals("Erro")) {
            resultado.setText("");
        } else if (!t.isEmpty()) {
            resultado.setText(t.substring(0, t.length() - 1));
        }
    }

